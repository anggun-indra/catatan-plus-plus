#!/usr/bin/env python3
"""Regenerate C/ObjC data tables from the upstream Notepad++ source tree.

Reads:
  src/PowerEditor/src/langs.model.xml                        -> keywords + extension map
  src/PowerEditor/src/stylers.model.xml                      -> colour themes
  src/PowerEditor/src/ScintillaComponent/ScintillaEditView.cpp -> lang/lexer table

Writes into macport/src/: Keywords.c, Theme.c, LexerMap.m, LangFromExt.m
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)                       # macport/
PROJECT = os.path.dirname(PORT)                    # repository root
SRC = os.path.join(PROJECT, "src")                 # upstream clone
OUT = os.path.join(PORT, "src")                    # port sources
PE = os.path.join(SRC, "PowerEditor", "src")

HEADER = "// Generated by tools/gen.py from notepad-plus-plus (GPLv3). Do not edit."


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def lang_table():
    """_langNameInfoArray: lang name, short label, long label, LangType, lexer id."""
    src = read(os.path.join(PE, "ScintillaComponent", "ScintillaEditView.cpp"))
    start = src.index("_langNameInfoArray[L_EXTERNAL + 1] = {")
    body = src[start:src.index("};", start)]
    return re.findall(
        r'\{L"([^"]*)",\s*L"([^"]*)",\s*L"([^"]*)",\s*(L_[A-Z0-9_]+),\s*"([^"]*)"\}',
        body,
    )


def ext_map():
    """extension -> langs.model.xml language name."""
    src = read(os.path.join(PE, "langs.model.xml"))
    out = {}
    for name, exts in re.findall(r'<Language name="([^"]+)" ext="([^"]*)"', src):
        for e in exts.split():
            out.setdefault(e.lower(), name)
    return out


def keywords():
    """language -> {keyword list index: words}."""
    src = read(os.path.join(PE, "langs.model.xml"))
    idx = {"instre1": 0, "instre2": 1}
    idx.update({"type%d" % n: n + 1 for n in range(1, 8)})
    idx.update({"substyle%d" % n: n + 8 for n in range(1, 9)})

    out = {}
    for name, body in re.findall(r'<Language name="([^"]+)"(.*?)</Language>', src, re.S):
        sets = {}
        for k, v in re.findall(r'<Keywords name="([^"]+)">([^<]*)</Keywords>', body):
            if k in idx and v.strip():
                sets[idx[k]] = " ".join(v.split())
        if sets:
            out[name] = sets
    return out


def themes():
    """lexer type name -> [(styleID, fg, bg, bold, italic)]."""
    src = read(os.path.join(PE, "stylers.model.xml"))
    out = {}
    for name, body in re.findall(r'<LexerType name="([^"]*)"[^>]*>(.*?)</LexerType>', src, re.S):
        entries = []
        for attrs in re.findall(r"<WordsStyle ([^/]*)/>", body):
            a = dict(re.findall(r'(\w+)="([^"]*)"', attrs))
            try:
                sid = int(a.get("styleID", "-1"))
            except ValueError:
                continue
            fg, bg = a.get("fgColor", ""), a.get("bgColor", "")
            if len(fg) != 6 or len(bg) != 6:
                continue
            fs = int(a.get("fontStyle", "0") or 0)
            entries.append((sid, fg, bg, fs & 1, (fs >> 1) & 1))
        if entries:
            out[name] = entries
    return out


def ident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def emit_keywords(langs, lexers, kw):
    out = [HEADER, '#import "Keywords.h"', "#include <stddef.h>", "#include <string.h>", "",
           "typedef struct { int list; const char *words; } KwSet;",
           "typedef struct { const char *lang; const char *lexer; const KwSet *sets;"
           " int count; } KwLang;", ""]
    rows = []
    for name in sorted(kw):
        lexer = lexers.get(name)
        if not lexer:
            continue
        sym = "kw_" + ident(name)
        out.append("static const KwSet %s[] = {" % sym)
        for i in sorted(kw[name]):
            w = kw[name][i].replace("\\", "\\\\").replace('"', '\\"')
            out.append('    {%d, "%s"},' % (i, w))
        out.append("};")
        out.append("")
        rows.append((name, lexer, sym, len(kw[name])))

    out.append("static const KwLang kLangKw[] = {")
    for name, lexer, sym, n in rows:
        out.append('    {"%s", "%s", %s, %d},' % (name, lexer, sym, n))
    out.append("};")
    out.append("""
const char *KeywordsForLang(const char *lang, int list) {
    for (size_t i = 0; i < sizeof(kLangKw) / sizeof(kLangKw[0]); i++) {
        if (strcmp(kLangKw[i].lang, lang) != 0) continue;
        for (int j = 0; j < kLangKw[i].count; j++)
            if (kLangKw[i].sets[j].list == list)
                return kLangKw[i].sets[j].words;
        return NULL;
    }
    return NULL;
}

const char *LexerIdForLang(const char *lang) {
    for (size_t i = 0; i < sizeof(kLangKw) / sizeof(kLangKw[0]); i++)
        if (strcmp(kLangKw[i].lang, lang) == 0) return kLangKw[i].lexer;
    return NULL;
}""")
    with open(os.path.join(OUT, "Keywords.c"), "w") as f:
        f.write("\n".join(out) + "\n")
    return len(rows)


def emit_theme(th):
    out = [HEADER, '#import "Theme.h"', "#include <stddef.h>", "#include <string.h>", "",
           "typedef struct { const char *lexer; const StyleDef *styles; int count; } LexerTheme;",
           ""]
    rows = []
    for name in sorted(th):
        sym = "th_" + ident(name)
        out.append("static const StyleDef %s[] = {" % sym)
        for sid, fg, bg, bold, ital in th[name]:
            out.append("    {%d, 0x%s, 0x%s, %d, %d}," % (sid, fg, bg, bold, ital))
        out.append("};")
        out.append("")
        rows.append((name, sym, len(th[name])))

    out.append("static const LexerTheme kThemes[] = {")
    for name, sym, n in rows:
        out.append('    {"%s", %s, %d},' % (name, sym, n))
    out.append("};")
    out.append("""
const StyleDef *ThemeForLexer(const char *lexer, int *count) {
    for (size_t i = 0; i < sizeof(kThemes) / sizeof(kThemes[0]); i++) {
        if (strcmp(kThemes[i].lexer, lexer) == 0) {
            if (count) *count = kThemes[i].count;
            return kThemes[i].styles;
        }
    }
    if (count) *count = 0;
    return NULL;
}""")
    with open(os.path.join(OUT, "Theme.c"), "w") as f:
        f.write("\n".join(out) + "\n")
    return len(rows)


def emit_maps(table, ext, lexers):
    pairs = sorted((e, n) for e, n in ext.items() if n in lexers)

    lex = [HEADER, '#import "LexerMap.h"', "#include <string.h>",
           '#include "ILexer.h"', '#include "Lexilla.h"', "",
           "typedef struct { const char *ext; const char *lexer; } ExtLexer;", "",
           "static const ExtLexer kExtMap[] = {"]
    for e, n in pairs:
        lex.append('    {"%s", "%s"},' % (e, lexers[n]))
    lex.append("};")
    lex.append("")

    langs = [(n, label) for n, label, _, _, _ in table if n in lexers]
    lex.append("typedef struct { const char *id; const char *label; } LangEntry;")
    lex.append("static const LangEntry kLangs[] = {")
    lex.append('    {"normal", "Normal text"},')
    for n, label in langs:
        lex.append('    {"%s", "%s"},' % (n, label.replace('"', '\\"')))
    lex.append("};")
    lex.append("""
NSString *LexerNameForExtension(NSString *extension) {
    if (extension.length == 0) return @"null";
    const char *e = [extension.lowercaseString UTF8String];
    for (size_t i = 0; i < sizeof(kExtMap) / sizeof(kExtMap[0]); i++)
        if (strcmp(kExtMap[i].ext, e) == 0)
            return [NSString stringWithUTF8String:kExtMap[i].lexer];
    return @"null";
}

NSArray<NSString *> *AllLexerNames(void) {
    NSMutableArray *a = [NSMutableArray array];
    int n = GetLexerCount();
    for (int i = 0; i < n; i++) {
        char b[128] = {0};
        GetLexerName(i, b, sizeof(b));
        [a addObject:[NSString stringWithUTF8String:b]];
    }
    return a;
}

NSArray<NSString *> *NppLanguageIDs(void) {
    NSMutableArray *a = [NSMutableArray array];
    for (size_t i = 0; i < sizeof(kLangs) / sizeof(kLangs[0]); i++)
        [a addObject:[NSString stringWithUTF8String:kLangs[i].id]];
    return a;
}

NSString *NppLanguageLabel(NSString *langID) {
    const char *c = [langID UTF8String];
    for (size_t i = 0; i < sizeof(kLangs) / sizeof(kLangs[0]); i++)
        if (strcmp(kLangs[i].id, c) == 0)
            return [NSString stringWithUTF8String:kLangs[i].label];
    return langID;
}""")
    with open(os.path.join(OUT, "LexerMap.m"), "w") as f:
        f.write("\n".join(lex) + "\n")

    le = [HEADER, '#import "LexerMap.h"', "#include <string.h>", "",
          "typedef struct { const char *ext; const char *lang; } ExtLang;", "",
          "static const ExtLang kExtLang[] = {"]
    for e, n in pairs:
        le.append('    {"%s", "%s"},' % (e, n))
    le.append("};")
    le.append("""
NSString *NppLanguageForExtension(NSString *extension) {
    if (extension.length == 0) return @"normal";
    const char *e = [extension.lowercaseString UTF8String];
    for (size_t i = 0; i < sizeof(kExtLang) / sizeof(kExtLang[0]); i++)
        if (strcmp(kExtLang[i].ext, e) == 0)
            return [NSString stringWithUTF8String:kExtLang[i].lang];
    return @"normal";
}""")
    with open(os.path.join(OUT, "LangFromExt.m"), "w") as f:
        f.write("\n".join(le) + "\n")
    return len(pairs), len(langs) + 1


def main():
    table = lang_table()
    lexers = {name: lexer for name, _, _, _, lexer in table if lexer != "null"}
    table = [r for r in table if r[0] in lexers]

    n_kw = emit_keywords(table, lexers, keywords())
    n_th = emit_theme(themes())
    n_ext, n_lang = emit_maps(table, ext_map(), lexers)

    print("Keywords.c   %d languages" % n_kw)
    print("Theme.c      %d lexer themes" % n_th)
    print("LexerMap.m   %d languages, LangFromExt.m %d extensions" % (n_lang, n_ext))


if __name__ == "__main__":
    sys.exit(main())
